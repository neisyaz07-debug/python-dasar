# List (dapat diubah / mutable)
buah = ["Apel", "Jeruk", "Mangga"]
buah.append("Pisang")
print("List:", buah)

# Tuple (tidak dapat diubah / immutable)
koordinat = (-6.9175, 107.6191)
print("Tuple:", koordinat)

# Set (unik, otomatis menghapus duplikat)
angka_unik = {1, 2, 2, 3, 4, 4, 5}
print("Set:", angka_unik)
