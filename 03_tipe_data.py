# Tipe Data Dasar Python
nama = "Neisya"          # String (str)
umur = 19                # Integer (int)
tinggi = 160.5           # Float (float)
mahasiswa_aktif = True   # Boolean (bool)

print(f"Nama: {nama} ({type(nama).__name__})")
print(f"Umur: {umur} ({type(umur).__name__})")
print(f"Tinggi: {tinggi} ({type(tinggi).__name__})")
print(f"Status Aktif: {mahasiswa_aktif} ({type(mahasiswa_aktif).__name__})")
